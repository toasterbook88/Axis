func TestDaemonTokenSourceEnvVarIsFixed(t *testing.T) {
	home := t.TempDir()
	t.Setenv(persist.AxisHomeEnv, home)
	t.Setenv(TokenEnvVar, tokA)

	src, err := newDaemonTokenSource(context.Background(), time.Millisecond)
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := src.TokenSource.(StaticToken); !ok {
		t.Fatalf("with %s set, source = %T, want StaticToken", TokenEnvVar, src.TokenSource)
	}
	if got := src.Current(); got != tokA {
		t.Fatalf("Current() = %q, want the env token", got)
	}
	// The env case never touches the token file and has no poller to drain.
	if _, err := os.Stat(filepath.Join(home, "token")); !os.IsNotExist(err) {
		t.Fatalf("env-var source touched the token file (stat err=%v)", err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), time.Second)
	defer cancel()
	src.WaitStopped(ctx)
	if ctx.Err() != nil {
		t.Fatal("WaitStopped blocked for the env-var source")
	}
}

func TestDaemonTokenSourceCreatesThenReloadsFile(t *testing.T) {
	home := t.TempDir()
	t.Setenv(persist.AxisHomeEnv, home)
	t.Setenv(TokenEnvVar, "")
	path := filepath.Join(home, "token")

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	src, err := newDaemonTokenSource(ctx, 5*time.Millisecond)
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := src.TokenSource.(*FileToken); !ok {
		t.Fatalf("without %s, source = %T, want *FileToken", TokenEnvVar, src.TokenSource)
	}
	// First start creates the file, and the source serves what it wrote.
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("token file not created on first start: %v", err)
	}
	if got, _ := parseToken(data); got == "" || got != src.Current() {
		t.Fatal("source does not serve the token written on first start")
	}

	writeTokenFile(t, path, tokB)
	deadline := time.Now().Add(2 * time.Second)
	for src.Current() != tokB {
		if time.Now().After(deadline) {
			t.Fatal("daemon token source did not reload the rewritten file")
		}
		time.Sleep(5 * time.Millisecond)
	}

	cancel()
	waitCtx, waitCancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer waitCancel()
	src.WaitStopped(waitCtx)
	if waitCtx.Err() != nil {
		t.Fatal("poller did not stop after ctx cancel")
	}
}

func TestDaemonTokenSourceIgnoresInvalidFileOnStart(t *testing.T) {
	// An invalid file at startup is regenerated by the loader (same rule as
	// clients), so the source always starts with a valid token.
	home := t.TempDir()
	t.Setenv(persist.AxisHomeEnv, home)
	t.Setenv(TokenEnvVar, "")
	if err := os.WriteFile(filepath.Join(home, "token"), []byte("not-a-token"), 0o600); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	src, err := newDaemonTokenSource(ctx, time.Hour)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := parseToken([]byte(src.Current())); err != nil {
		t.Fatalf("source started with an invalid token: %v", err)
	}
}
